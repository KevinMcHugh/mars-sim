// Regenerates shared/defaults.js, Scum Lab's baked-in copy of the cognition
// defaults, from the game's own: `go run . -print-cognition-config` (the
// shipped reactions, perceptions, trait rules, focuses and attractors) and
// `go run . -print-cognition-vocab` (the vocabulary). The copy used to be kept
// by hand and drifted: it lost every reaction added after it was written, and
// its focuses kept a key the lab no longer reads. Run it from the repo root
// after any change to the Go cognition defaults:
//
//   node tools/scum-lab/gen-defaults.mjs          rewrite the file
//   node tools/scum-lab/gen-defaults.mjs --check  fail if it is out of date

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseYAML } from "./shared/yaml.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const out = join(here, "shared", "defaults.js");

const go = (flag) => execFileSync("go", ["run", ".", flag], { cwd: root, encoding: "utf8", maxBuffer: 1 << 24 });
const vocab = JSON.parse(go("-print-cognition-vocab")).vocabulary;
const empty = {
  vocabulary: vocab, attractors: {}, focuses: {}, arbitration: {},
  perceptions: [], reactions: {}, trait_rules: [],
};
const config = parseYAML(go("-print-cognition-config"), empty);
config.schema_version = 1;
config.vocabulary = vocab;

// The outlook traits' affect homes (personality.go): the lab's focus bench
// starts a colonist there. They are not in the cognition file.
const traitHomes = {
  optimist: { charge: 0, grip: 8, valence: 25 },
  pessimist: { charge: 0, grip: -8, valence: -25 },
};

const json = (value) => JSON.stringify(value, null, 2);
const text = `// GENERATED by tools/scum-lab/gen-defaults.mjs from the game's Go cognition
// defaults. Do not edit: change the Go defaults and rerun it (see its header).
// Importing a file in the lab replaces this at runtime.

const DEFAULT_CONFIG = ${json(config)};

const DEFAULT_VOCABULARY = ${json(vocab)};

const DEFAULT_PERCEPTIONS = JSON.parse(JSON.stringify(DEFAULT_CONFIG.perceptions));

const TRAIT_HOMES = ${json(traitHomes)};

export {
  DEFAULT_CONFIG,
  DEFAULT_VOCABULARY,
  DEFAULT_PERCEPTIONS,
  TRAIT_HOMES,
};
`;

if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    console.error("tools/scum-lab/shared/defaults.js is out of date: run node tools/scum-lab/gen-defaults.mjs");
    process.exit(1);
  }
  console.log("defaults.js is current");
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}: ${Object.keys(config.reactions).length} reactions, ${config.trait_rules.length} trait rules`);
}
